"""Reports router: PDF generation with fpdf2 (the Python port of FPDF)."""

from typing import Annotated

from fastapi import APIRouter, Depends
from fastapi.responses import Response
from fpdf import FPDF

from ..deps import DbSessionDep, log_event, require_permission
from ..models import User

router = APIRouter(prefix="/api/reports", tags=["reports"])

_LOGO = "static/images/banner.jpeg"


class UsersReport(FPDF):
    """PDF report of users, mirroring the original ReportesFPDF layout."""

    def header(self):
        self.set_fill_color(0, 132, 255)
        self.set_text_color(255)
        self.set_draw_color(0, 132, 255)
        self.set_line_width(0.3)
        self.set_font("Helvetica", "B", 14)
        self.cell(0, 10, "Kajataca Inventory - Users Report", ln=True, align="C")
        self.ln(4)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(0)
        self.cell(0, 6, "Generated by the inventory system", ln=True, align="C")
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}}", align="C")

    def users_table(self, header, rows, widths):
        self.set_fill_color(0, 132, 255)
        self.set_text_color(255)
        self.set_draw_color(0, 132, 255)
        self.set_line_width(0.3)
        self.set_font("Helvetica", "B", 10)
        for col, w in zip(header, widths):
            self.cell(w, 7, col, border=1, align="C", fill=True)
        self.ln()
        self.set_fill_color(224, 235, 255)
        self.set_text_color(0)
        self.set_font("Helvetica", "", 10)
        fill = False
        for row in rows:
            for value, w in zip(row, widths):
                self.cell(w, 6, str(value), border="LR", align="L", fill=fill)
            self.ln()
            fill = not fill
        self.cell(sum(widths), 0, "", border="T")


@router.get("/users")
def users_report(
    user: Annotated[User, Depends(require_permission("reports.view"))],
    db: DbSessionDep,
) -> Response:
    """Generate a PDF with the full user list."""
    users = db.query(User).order_by(User.id).all()
    header = ["Id", "Name", "Nick", "Status"]
    widths = [31, 62, 52, 40]
    rows = [
        [
            u.id,
            u.name,
            u.nick,
            "ACTIVE" if u.status else "INACTIVE",
        ]
        for u in users
    ]

    pdf = UsersReport(orientation="P", unit="mm", format="A4")
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.users_table(header, rows, widths)

    payload = pdf.output(dest="S")
    if isinstance(payload, str):
        payload = payload.encode("latin-1")
    elif isinstance(payload, bytearray):
        payload = bytes(payload)

    log_event(db, user, "generate_report", f"User report generated by '{user.nick}'")
    return Response(
        content=payload,
        media_type="application/pdf",
        headers={"Content-Disposition": 'attachment; filename="users_report.pdf"'},
    )
